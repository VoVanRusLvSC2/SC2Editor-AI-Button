"""Generate the C++ translation table from the bridge's shared locale catalog."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
catalog = json.loads((root / 'bridge/locales.json').read_text(encoding='utf-8'))
expected = {'deDE', 'esES', 'esMX', 'frFR', 'itIT', 'koKR', 'plPL', 'ptBR', 'zhCN', 'zhTW'}
if set(catalog) != expected:
    raise SystemExit('Unexpected set of translations')
keys = set(next(iter(catalog.values())))
if any(set(entries) != keys for entries in catalog.values()):
    raise SystemExit('Every language must have the same translation keys')

def wide(value):
    return 'L' + json.dumps(value, ensure_ascii=False)

lines = ['// Generated by scripts/generate_locales.py; edit bridge/locales.json instead.',
         '#pragma once', '#include <cwchar>', '',
         'struct LocalizedEntry { const wchar_t* key; const wchar_t* value; };']
for locale, entries in sorted(catalog.items()):
    lines.append(f'static const LocalizedEntry kLocale_{locale}[] = {{')
    lines.extend('    {' + wide(key) + ',' + wide(value) + '},' for key, value in sorted(entries.items()))
    lines.append('};')
lines.extend(['', 'inline const wchar_t* TranslateText(const wchar_t* locale, const wchar_t* ru, const wchar_t* en) {',
              '    if (!locale || !en) return en;',
              '    if (!wcscmp(locale,L"ruRU") || !wcscmp(locale,L"ru")) return ru;',
              '    const LocalizedEntry* entries=nullptr; size_t count=0;'])
for locale in sorted(catalog):
    lines.append(f'    if (!wcscmp(locale,L"{locale}")) {{ entries=kLocale_{locale}; count=sizeof(kLocale_{locale})/sizeof(kLocale_{locale}[0]); }}')
lines.extend(['    for(size_t i=0;i<count;++i) if(!wcscmp(entries[i].key,en)) return entries[i].value;',
              '    return en;', '}', ''])
(root / 'src/locales_generated.h').write_text('\n'.join(lines),encoding='utf-8',newline='\n')
